"""Generate Python messages, type stubs and public import modules from .proto."""
from __future__ import annotations

import argparse
import re
import shutil
import tempfile
from importlib.resources import files
from pathlib import Path

GENERATED = b"# Generated by scripts/generate_python.py. Do not edit.\n"

def generate(root: Path, output: Path | None = None) -> None:
    from google.protobuf import descriptor_pb2
    from grpc_tools import protoc

    root = root.resolve()
    output = (output or root / "build/python").resolve()
    if output == root or root.is_relative_to(output) or output.is_relative_to(root / "avoar"):
        raise ValueError("Generated output must be separate from the source package")
    schemas = sorted((root / "avoar/core/opendata").rglob("*.proto"))

    if not schemas:
        raise RuntimeError("No Protobuf schemas found")

    with tempfile.TemporaryDirectory(prefix="avoar-protobuf-") as directory:
        staging = Path(directory)
        descriptor_path = staging / "schema.pb"

        result = protoc.main([
            "protoc",
            f"--proto_path={root}",
            f"--proto_path={files('grpc_tools').joinpath('_proto')}",
            f"--python_out={staging}",
            f"--pyi_out={staging}",
            f"--descriptor_set_out={descriptor_path}",
            *[p.relative_to(root).as_posix() for p in schemas],
        ])

        if result:
            raise RuntimeError(f"Protobuf compilation failed (exit {result})")
        descriptors = descriptor_pb2.FileDescriptorSet.FromString(descriptor_path.read_bytes())

        for schema in descriptors.file:
            relative = Path(schema.name)

            if relative.name != "domain.proto":
                continue

            module = ".".join(relative.with_suffix("").parts) + "_pb2"
            lines = ['"""Generated from domain.proto. Do not edit."""', "from enum import IntEnum", ""]
            exports = []

            for message in schema.message_type:
                name = message.name
                lines.append(f"from {module} import {name} as {name}")
                exports.append(name)

            for enum in schema.enum_type:
                prefix = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", enum.name).upper() + "_"
                lines.extend(["", f"class {enum.name}(IntEnum):"])
                for value in enum.value:
                    lines.append(f"    {value.name.removeprefix(prefix)} = {value.number}")
                exports.append(enum.name)

            if relative.parent.name == "common":
                lines.extend(["", "# Compatibility alias; uint64 bounds are enforced by message fields.", "id_avoar = int"])
                exports.append("id_avoar")

            lines.extend(["", f"__all__ = {exports!r}", ""])

            facade = staging / relative.with_suffix(".py")
            facade.write_text("\n".join(lines))

            # Expose the same API from both business and business.domain.
            init = facade.parent / "__init__.py"
            init.write_text('"""Generated public exports. Do not edit."""\n'
                'from pkgutil import extend_path\n'
                '__path__ = extend_path(__path__, __name__)\n' + "".join(
                f"from .domain import {name} as {name}\n" for name in exports
            ) + f"\n__all__ = {exports!r}\n")

        # Remove outputs of deleted schemas, but only files owned by this generator.
        outputs = {
            source.relative_to(staging): source
            for source in staging.rglob("*")
            if source.is_file() and source.suffix in (".py", ".pyi")
        }

        for existing in (output / "avoar/core/opendata").rglob("*"):
            if existing.suffix not in (".py", ".pyi") or not existing.is_file():
                continue

            if existing.relative_to(output) not in outputs:
                with existing.open("rb") as stream:
                    if stream.readline() == GENERATED:
                        existing.unlink()

        # Compile everything before replacing outputs; failed compilation
        # leaves the previously generated files intact.
        for relative, source in sorted(outputs.items()):
            destination = output / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            content = GENERATED + source.read_bytes()

            if not destination.exists() or destination.read_bytes() != content:
                destination.write_bytes(content)

        (output / "avoar/core/py.typed").touch()


def clean(root: Path) -> None:
    """Remove manual output and legacy in-source files owned by this generator."""
    root = root.resolve()
    output = root / "build/python"
    if output.exists():
        shutil.rmtree(output)
    for path in (root / "avoar/core/opendata").rglob("*"):
        if not path.is_file() or path.suffix not in (".py", ".pyi"):
            continue
        with path.open("rb") as stream:
            owned = stream.readline() == GENERATED
        if owned:
            path.unlink()
            # Remove obsolete bytecode only for the removed generated module.
            cache = path.parent / "__pycache__"
            if path.suffix == ".py" and cache.is_dir():
                for bytecode in cache.glob(path.stem + ".*.pyc"):
                    bytecode.unlink()
    marker = root / "avoar/core/py.typed"
    if marker.is_file() and not marker.read_bytes():
        marker.unlink()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, help="Output directory (default: build/python)")
    parser.add_argument("--clean", action="store_true", help="Remove manual output and legacy generated source files")
    args = parser.parse_args()
    if args.clean:
        if args.output:
            parser.error("--clean uses the default output; do not combine with --output")
        clean(args.root)
    else:
        generate(args.root, args.output)
