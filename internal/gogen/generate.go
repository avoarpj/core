// Package gogen compiles the canonical contracts and generates consumer-local Go packages.
package gogen

import (
	"bytes"
	"context"
	_ "embed"
	"fmt"
	"go/format"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/bufbuild/protocompile"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
)

// PluginVersion also identifies the runtime dependency expected by generated code.
const PluginVersion = "v1.36.12"

const marker = "// Code generated by avoar-core-gen. DO NOT EDIT.\n"

//go:embed validation.go.tmpl
var validationTemplate string

//go:embed toolchain.mod
var toolchainModule []byte

//go:embed toolchain.sum
var toolchainSum []byte

// Runner executes the official protoc-gen-go plugin. Tests may provide a runner
// to inspect requests without invoking the Go toolchain.
type Runner func(context.Context, *pluginpb.CodeGeneratorRequest) (*pluginpb.CodeGeneratorResponse, error)

// RunPlugin runs a version-pinned generator independently of the consumer's module.
func RunPlugin(ctx context.Context, request *pluginpb.CodeGeneratorRequest) (*pluginpb.CodeGeneratorResponse, error) {
	data, err := proto.Marshal(request)
	if err != nil {
		return nil, err
	}
	directory, err := os.MkdirTemp("", "avoar-go-toolchain-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(directory)
	if err := os.WriteFile(filepath.Join(directory, "go.mod"), toolchainModule, 0o644); err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(directory, "go.sum"), toolchainSum, 0o644); err != nil {
		return nil, err
	}
	command := exec.CommandContext(ctx, "go", "run", "-mod=readonly", "google.golang.org/protobuf/cmd/protoc-gen-go")
	command.Dir = directory
	command.Env = append(os.Environ(), "GOWORK=off")
	command.Stdin = bytes.NewReader(data)
	var diagnostics bytes.Buffer
	command.Stderr = &diagnostics
	result, err := command.Output()
	if err != nil {
		return nil, fmt.Errorf("protoc-gen-go %s: %w\n%s", PluginVersion, err, diagnostics.String())
	}
	response := new(pluginpb.CodeGeneratorResponse)
	if err := proto.Unmarshal(result, response); err != nil {
		return nil, fmt.Errorf("decode protoc-gen-go output: %w", err)
	}
	return response, nil
}

// Generate keeps schema-relative paths and maps all imports into importPrefix.
// Compilation and plugin execution finish before existing outputs are changed.
func Generate(ctx context.Context, schemas fs.FS, output, importPrefix string, run Runner) error {
	importPrefix = strings.TrimSuffix(importPrefix, "/")
	if importPrefix == "" || strings.ContainsAny(importPrefix, " \\,:;\n\r\t") || strings.HasPrefix(importPrefix, "/") {
		return fmt.Errorf("provide a Go import prefix, e.g. example.com/app/internal/core")
	}
	for _, part := range strings.Split(importPrefix, "/") {
		if part == "" || part == "." || part == ".." {
			return fmt.Errorf("invalid Go import prefix %q", importPrefix)
		}
	}
	var names []string
	if err := fs.WalkDir(schemas, "avoar/core/opendata", func(name string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() && strings.HasSuffix(name, ".proto") {
			names = append(names, name)
		}
		return nil
	}); err != nil {
		return err
	}
	if len(names) == 0 {
		return fmt.Errorf("no Protobuf schemas found")
	}
	sort.Strings(names)
	for _, name := range names {
		if _, err := os.Stat(filepath.Join(output, filepath.FromSlash(name))); err == nil {
			return fmt.Errorf("output contains source schema %s; choose a separate generated directory", name)
		} else if !os.IsNotExist(err) {
			return err
		}
	}
	compiler := protocompile.Compiler{
		Resolver: protocompile.WithStandardImports(&protocompile.SourceResolver{
			Accessor: func(name string) (io.ReadCloser, error) { return schemas.Open(name) },
		}),
		SourceInfoMode: protocompile.SourceInfoStandard,
	}
	compiled, err := compiler.Compile(ctx, names...)
	if err != nil {
		return fmt.Errorf("compile schemas: %w", err)
	}
	parameters := []string{"paths=source_relative"}
	for _, name := range names {
		parameters = append(parameters, "M"+name+"="+importPrefix+"/"+path.Dir(name))
	}
	request := &pluginpb.CodeGeneratorRequest{FileToGenerate: names, Parameter: proto.String(strings.Join(parameters, ","))}
	seen := map[string]bool{}
	var visit func(protoreflect.FileDescriptor)
	visit = func(file protoreflect.FileDescriptor) {
		if seen[file.Path()] {
			return
		}
		seen[file.Path()] = true
		for index := 0; index < file.Imports().Len(); index++ {
			visit(file.Imports().Get(index).FileDescriptor)
		}
		request.ProtoFile = append(request.ProtoFile, protodesc.ToFileDescriptorProto(file))
	}
	for _, file := range compiled {
		visit(file)
	}
	response, err := run(ctx, request)
	if err != nil {
		return err
	}
	if response.GetError() != "" {
		return fmt.Errorf("protoc-gen-go: %s", response.GetError())
	}
	outputs := map[string][]byte{}
	for _, file := range response.File {
		name := file.GetName()
		if !fs.ValidPath(name) || !strings.HasPrefix(name, "avoar/core/opendata/") || !strings.HasSuffix(name, ".pb.go") || file.GetInsertionPoint() != "" {
			return fmt.Errorf("unexpected generated filename %q", name)
		}
		outputs[name] = []byte(marker + file.GetContent())
	}
	if len(outputs) != len(names) {
		return fmt.Errorf("expected %d generated files, got %d", len(names), len(outputs))
	}
	helpers, err := format.Source([]byte(strings.ReplaceAll(validationTemplate, "{{IMPORT_PREFIX}}", importPrefix)))
	if err != nil {
		return fmt.Errorf("format validation helpers: %w", err)
	}
	outputs["avoar/core/validation/validation.go"] = append([]byte(marker), helpers...)
	return writeOutputs(output, outputs)
}

func writeOutputs(output string, outputs map[string][]byte) error {
	// Check for collisions and symlinks before writing any files.
	for name, content := range outputs {
		destination := filepath.Join(output, filepath.FromSlash(name))
		for current := destination; ; current = filepath.Dir(current) {
			info, err := os.Lstat(current)
			if err != nil && !os.IsNotExist(err) {
				return err
			}
			if err == nil && info.Mode()&os.ModeSymlink != 0 {
				return fmt.Errorf("refusing symlink output %s", current)
			}
			if filepath.Dir(current) == current {
				break
			}
		}
		old, err := os.ReadFile(destination)
		if err == nil && !bytes.HasPrefix(old, []byte(marker)) && !bytes.Equal(old, content) {
			return fmt.Errorf("refusing to overwrite handwritten file %s", destination)
		}
		if err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	for name, content := range outputs {
		destination := filepath.Join(output, filepath.FromSlash(name))
		old, _ := os.ReadFile(destination)
		if bytes.Equal(old, content) {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(destination, content, 0o644); err != nil {
			return err
		}
	}
	return removeOwned(output, outputs)
}

// Clean removes only files marked as owned by this generator, preserving user code.
func Clean(output string) error { return removeOwned(output, nil) }

func removeOwned(output string, keep map[string][]byte) error {
	if _, err := os.Stat(output); os.IsNotExist(err) {
		return nil
	} else if err != nil {
		return err
	}
	return filepath.WalkDir(output, func(name string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || entry.Type()&os.ModeSymlink != 0 {
			return nil
		}
		relative, err := filepath.Rel(output, name)
		if err != nil {
			return err
		}
		if _, ok := keep[filepath.ToSlash(relative)]; ok {
			return nil
		}
		content, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(content, []byte(marker)) {
			return os.Remove(name)
		}
		return nil
	})
}
